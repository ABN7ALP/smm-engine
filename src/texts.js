function name(ctx) {
  return (ctx.from?.first_name || 'صديقي').trim();
}

module.exports = {
  startFree(ctx, options) {
    return `أهلاً ${name(ctx)}.

عندي لك تجربة مجانية محترمة لمشاهدات تيك توك:
اختر الآن: ${options.join(' أو ')} مشاهدة مجاناً.

بدون تسجيل، وبدون دفع.

اختر الكمية من الأزرار بالأسفل.`;
  },

  askLink(ctx) {
    return `تمام ${name(ctx)}.
أرسل رابط فيديو تيك توك الآن.`;
  },

  invalidLink() {
    return `الرابط غير صالح.
أرسله كرابط تيك توك مباشر مثل:
https://www.tiktok.com/@user/video/123456789`;
  },

  preview(ctx, amount, url, videoId) {
    return `راجع الطلب يا ${name(ctx)}:

الرابط:
${url}

معرف الفيديو:
${videoId || 'غير ظاهر'}

الكمية:
${amount} مشاهدة

وقت التنفيذ المتوقع:
5 إلى 15 دقائق

إذا كل شيء صحيح: أكد الطلب الآن.`;
  },

  confirmedOnly(ctx) {
    return `تم يا ${name(ctx)}.
دخلنا طلبك بالتنفيذ الآن.
ستلاحظ الزيادة خلال 5 إلى 15 دقائق غالباً.

والآن سأترك لك عدّاد متابعة بسيط.`;
  },

  pending(ctx, minutes, siteUrl) {
    return `يا ${name(ctx)} طلبك قيد التنفيذ.
تقريباً خلال ${minutes} دقيقة بيكون خلص.

لو بدك كميات أكبر فوراً:
${siteUrl}`;
  },

  blocked(ctx, siteUrl) {
    return `يا ${name(ctx)} خلّينا نخلص الطلب الحالي أول.

إذا بدك كميات أكبر أو طلبات متعددة:
${siteUrl}`;
  },

  noMoreFree(ctx, siteUrl, inviteLink) {
    return `يا ${name(ctx)}، عرض المشاهدات المجاني انتهى.

بس عندي لك حلّين “كفو”:
1) إذا بدك مشاهدات/لايكات/متابعين بسرعة وبخيارات كثيرة:
هذا موقعنا الرسمي، وفيه خدمات كاملة، وأحياناً عروض مجانية أو تخفيضات توصل 90% وأكثر:
${siteUrl}

2) وإذا بدك تكمل مجاناً:
رابط دعوتك بالأسفل. كل دعوة ناجحة لشخص يستخدم البوت تعطيك 1000 مشاهدة إضافية:
${inviteLink}`;
  },

  offerAfterOneMinute(ctx, siteUrl, inviteLink) {
    return `يا ${name(ctx)}… عندي عرض كفو إلك من “ذكاء اصطناعي” لمستخدم يحب الشهرة.

إذا بدك مشاهدات أو لايكات أو متابعين بسرعة:
موقعنا الرسمي عليه كل الخدمات، ولا تنسى… أحياناً ننزل عروض مجانية أو تخفيضات توصل 90% وأكثر.
روح زور الموقع، مو خسران شي، يمكن يعجبك:

${siteUrl}

أو إذا ما بدك تدخل بتفاصيل:
عندي عرض مغري… كل دعوة ناجحة لصديقك يستخدم البوت تقدر تطلب بعدها 1000 مشاهدة مجانيّة.
هذا رابط دعوتك:
${inviteLink}

شو رأيك؟`;
  },

  offerReminder(ctx) {
    return `تذكير سريع يا ${name(ctx)}:
إذا بدك تكمل بزيادة أقوى أو تستفيد من عروضنا، شوف الرسالة السابقة وخيارات الموقع/الدعوات.`;
  },

  referralSuccessToReferrer(referrerFirstName, tokensNow) {
    const who = (referrerFirstName || 'صديقي').trim();
    return `مبروك يا ${who}.
دعوتك نجحت، وانضافت لك مكافأة 5000 مشاهدة.

صار عندك الآن ${tokensNow} مكافأة/مكافآت جاهزة.
اضغط /start واختر "5000 مشاهدة مكافأة" وابعث رابط الفيديو.`;
  }
};
